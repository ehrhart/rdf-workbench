import type { Metadata, Viewport } from 'next'
import { Open_Sans } from 'next/font/google'
import type React from 'react'
import { Toaster } from 'sonner'
import { ThemeProvider } from '@/components/theme-provider'
import { TooltipProvider } from '@/components/ui/tooltip'
import {
  getAppearanceAssetMeta,
  getAppearanceSettings,
  getInstanceName
} from '@/lib/appearance/appearance-settings'
import { buildAppearanceCss } from '@/lib/appearance/tokens'

import './globals.css'

const openSans = Open_Sans({ subsets: ['latin'] })

export async function generateMetadata(): Promise<Metadata> {
  const [appName, logoMeta] = await Promise.all([
    getInstanceName(),
    getAppearanceAssetMeta('logo')
  ])
  const metadata: Metadata = {
    title: {
      default: appName,
      template: `%s | ${appName}`
    },
    description: 'A workbench for exploring RDF triplestores'
  }
  if (logoMeta) {
    const url = `/api/appearance/logo?v=${logoMeta.updatedAt}`
    metadata.icons =
      logoMeta.mime === 'image/svg+xml'
        ? { icon: { url, type: logoMeta.mime } }
        : {
            icon: { url, type: logoMeta.mime },
            apple: { url, type: logoMeta.mime }
          }
  } else {
    // A second icon link (e.g. from the app/icon.svg convention) makes the
    // favicon depend on which link the browser picks.
    metadata.icons = { icon: { url: '/brand-icon.svg', type: 'image/svg+xml' } }
  }
  return metadata
}

export async function generateViewport(): Promise<Viewport> {
  const settings = await getAppearanceSettings()
  return settings.primaryColor ? { themeColor: settings.primaryColor } : {}
}

export default async function RootLayout({
  children
}: {
  children: React.ReactNode
}) {
  const settings = await getAppearanceSettings()
  const appearanceCss = buildAppearanceCss(settings)

  return (
    <html lang="en" suppressHydrationWarning>
      <body className={`${openSans.className} antialiased`}>
        {appearanceCss && (
          // globals.css defines the same variables on :root and .dark, and
          // later declarations win. This style tag renders after it.
          // biome-ignore lint/security/noDangerouslySetInnerHtml: the CSS is generated by deriveTokens from validated settings, never user-supplied markup
          <style dangerouslySetInnerHTML={{ __html: appearanceCss }} />
        )}
        <ThemeProvider
          attribute="class"
          defaultTheme={settings.defaultMode}
          enableSystem
        >
          <TooltipProvider delayDuration={250} disableHoverableContent>
            {children}
            <Toaster />
          </TooltipProvider>
        </ThemeProvider>
      </body>
    </html>
  )
}
